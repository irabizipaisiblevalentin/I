"""Amategeko — CLI commands for MOBILE."""

from __future__ import annotations

import argparse
import os
import sys
from typing import Any


def kongera_iyobokamana(subparsers: Any) -> None:
    """Register mobile CLI subparsers."""
    mob_parser = subparsers.add_parser(
        "mobile",
        help="Mobile framework commands",
        description="Mobile framework commands for the I Programming Language",
    )

    mob_sub = mob_parser.add_subparsers(
        dest="mobile_command",
        help="Mobile subcommands",
        metavar="MOBILE_COMMAND",
    )

    p_gushya = mob_sub.add_parser(
        "gushya",
        help="Create a new mobile project",
    )
    p_gushya.add_argument("izina", help="Name of the mobile project")
    p_gushya.set_defaults(mobile_func=_gushya)

    p_genda = mob_sub.add_parser(
        "genda",
        help="Run a mobile app",
    )
    p_genda.add_argument("inzira", help="Path to .i file")
    p_genda.set_defaults(mobile_func=_genda)

    p_kubaka = mob_sub.add_parser(
        "kubaka",
        help="Build the project",
    )
    p_kubaka.add_argument("inzira", nargs="?", default=".", help="Path to project")
    p_kubaka.set_defaults(mobile_func=_kubaka)

    p_gupakira = mob_sub.add_parser(
        "gupakira",
        help="Package the app (apk/aab/ipa/debug)",
    )
    p_gupakira.add_argument("imiterere", choices=["apk", "aab", "ipa", "debug"], help="Package format")
    p_gupakira.set_defaults(mobile_func=_gupakira)

    p_emulator = mob_sub.add_parser(
        "emulator",
        help="Launch emulator",
    )
    p_emulator.add_argument("ikinyabiziga", choices=["android", "ios"], help="Target platform")
    p_emulator.set_defaults(mobile_func=_emulator)

    p_isuzuma = mob_sub.add_parser(
        "isuzuma",
        help="Doctor/diagnostics",
    )
    p_isuzuma.add_argument("inzira", nargs="?", default=".", help="Path to project")
    p_isuzuma.set_defaults(mobile_func=_isuzuma)

    p_profiler = mob_sub.add_parser(
        "profiler",
        help="Profile the app",
    )
    p_profiler.set_defaults(mobile_func=_profiler)

    p_ingingo = mob_sub.add_parser(
        "ingingo",
        help="List available components",
    )
    p_ingingo.set_defaults(mobile_func=_ingingo)

    p_gufasha = mob_sub.add_parser(
        "gufasha",
        help="Show mobile help",
    )
    p_gufasha.set_defaults(mobile_func=_gufasha)


def genda(args: argparse.Namespace) -> int:
    """Main dispatch function for mobile commands."""
    if not hasattr(args, "mobile_func"):
        print("Usage: isoko mobile <command> [options]")
        print()
        print("Available commands:")
        print("  gushya <izina>       Create a new mobile project")
        print("  genda <inzira.i>     Run a mobile app")
        print("  kubaka [inzira]      Build the project")
        print("  gupakira <imiterere> Package (apk/aab/ipa/debug)")
        print("  emulator <platform>  Launch emulator (android/ios)")
        print("  isuzuma [inzira]     Doctor/diagnostics")
        print("  profiler             Profile app")
        print("  ingingo              List available components")
        print("  gufasha              Show this help")
        return 0

    return args.mobile_func(args)


