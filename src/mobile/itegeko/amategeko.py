def _gushya(args: argparse.Namespace) -> int:
    """Create a new mobile project with a complete .i file template."""
    izina = args.izina
    inzira = os.path.join(os.getcwd(), izina)

    try:
        os.makedirs(inzira, exist_ok=True)
    except OSError as e:
        print(f"Error creating directory: {e}")
        return 1

    content = (
        f'# {izina} - Mobile App\n'
        f'# Auto-generated by isoko mobile gushya\n'
        f'\n'
        f'# Imports for all mobile components\n'
        f'import mobile.porogaramu\n'
        f'import mobile.ikiganiro\n'
        f'import mobile.ubugenzuzi\n'
        f'import mobile.ibikoresho.buto\n'
        f'import mobile.ibikoresho.ikimenyetso\n'
        f'import mobile.ibikoresho.ifishi\n'
        f'import mobile.ibikoresho.ikarita\n'
        f'import mobile.ibikoresho.ishusho\n'
        f'import mobile.imiterere.inkingi\n'
        f'import mobile.imiterere.umurongo\n'
        f'import mobile.imiterere.urusobete\n'
        f'import mobile.imiterere.itemba\n'
        f'import mobile.kamere.imiterere\n'
        f'import mobile.kamere.ibonwa\n'
        f'\n'
        f'# Activity setup\n'
        f'activity Inyandikorero extends Ikiganiro:\n'
        f'    izina: "{izina}"\n'
        f'    urugero: "https://i-lang.rw/app"\n'
        f'\n'
        f'    onCreate:\n'
        f'        self.title = "Murakaza neza"\n'
        f'        ibara = Ibara("Kanda buto kugirango utangire")\n'
        f'        buto = Buto(\n'
        f'            text="Tangira",\n'
        f'            variant=ButoVariant.PRIMARY,\n'
        f'            on_press=lambda: self.on_buto_kanda(),\n'
        f'        )\n'
        f'        inkingi = Inkingi(\n'
        f'            children=[ibara, buto],\n'
        f'            spacing=16,\n'
        f'            padding=24,\n'
        f'            alignment=Alignment.CENTER,\n'
        f'        )\n'
        f'        self.set_content(inkingi)\n'
        f'\n'
        f'    on_buto_kanda:\n'
        f'        self.title = "Watangiye!"\n'
        f'\n'
        f'# Navigation setup\n'
        f'ubugenzuzi = Ubugenzuzi()\n'
        f'ubugenzuzi.register_route(NavigationRoute(\n'
        f'    path="/home",\n'
        f'    name="home",\n'
        f'    params={"title": "Ahabanza"},\n'
        f'))\n'
        f'ubugenzuzi.register_route(NavigationRoute(\n'
        f'    path="/profile/:id",\n'
        f'    name="profile",\n'
        f'    animation="slide_from_right",\n'
        f'))\n'
        f'\n'
        f'# Sample UI with Column, Button, Text\n'
        f'inkingi = Inkingi(\n'
        f'    spacing=12,\n'
        f'    padding=16,\n'
        f'    alignment=Alignment.CENTER,\n'
        f')\n'
        f'umutwe = Umutwe("Murakaza neza", level=1)\n'
        f'ibara = Ibara("Iyi ni mobile app yawe ya mbere mu rurimi rw\'I.")\n'
        f'buto = Buto("Kanda hano", variant=ButoVariant.PRIMARY)\n'
        f'inkingi.add(umutwe)\n'
        f'inkingi.add(ibara)\n'
        f'inkingi.add(buto)\n'
        f'\n'
        f'# State management example\n'
        f'imibare = Imiterere(0)\n'
        f'\n'
        f'def ku_mibare_hinduka(old, new):\n'
        f'    print(f"Imibare yahindutse: {old} -> {new}")\n'
        f'\n'
        f'id = imibare.observe(ku_mibare_hinduka)\n'
        f'imibare.set(1)\n'
        f'imibare.set(5)\n'
        f'\n'
        f'# Reactive observable example\n'
        f'izina_ribonwa = Ibonwa("{izina}")\n'
        f'izina_ribonwa.when(\n'
        f'    condition=lambda v: len(v) > 0,\n'
        f'    callback=lambda v: print(f"Izina: {v}"),\n'
        f')\n'
        f'\n'
        f'# Application entry point\n'
        f'app = MobileApplication("{izina}", version="1.0.0")\n'
        f'app.register_activity(Inyandikorero())\n'
        f'app.run()\n'
    )

    filepath = os.path.join(inzira, f"{izina}.i")
    try:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"Created mobile project: {filepath}")
        return 0
    except OSError as e:
        print(f"Error writing file: {e}")
        return 1


def _genda(args: argparse.Namespace) -> int:
    """Run a mobile .i file."""
    inzira = args.inzira
    if not os.path.isfile(inzira):
        print(f"File not found: {inzira}")
        return 1
    print(f"Running mobile app: {inzira}")
    print("[MOBILE] App started (simulated — runtime pending)")
    return 0


def _kubaka(args: argparse.Namespace) -> int:
    """Build the project."""
    print(f"Building mobile project at: {args.inzira}")
    print("[MOBILE] Build complete (simulated)")
    return 0


def _gupakira(args: argparse.Namespace) -> int:
    """Package the app."""
    print(f"Packaging mobile app as {args.imiterere}...")
    print(f"[MOBILE] Package created: app.{args.imiterere} (simulated)")
    return 0


def _emulator(args: argparse.Namespace) -> int:
    """Launch an emulator."""
    ikinyabiziga = args.ikinyabiziga
    print(f"Launching {ikinyabiziga} emulator...")
    print(f"[MOBILE] {ikinyabiziga.capitalize()} emulator started (simulated)")
    return 0


def _isuzuma(args: argparse.Namespace) -> int:
    """Run diagnostics on a project."""
    import platform
    import shutil

    print("MOBILE Doctor / Diagnostics")
    print("=" * 40)
    print(f"Project path:      {os.path.abspath(args.inzira)}")
    print(f"Python version:    {platform.python_version()}")
    print(f"Platform:          {platform.system()} {platform.release()}")
    print(f"Node (for JS):     {shutil.which('node') or 'not found'}")
    print(f"Java (for Android): {shutil.which('java') or 'not found'}")
    print(f"Xcode (for iOS):   {'found' if platform.system() == 'Darwin' else 'not available'}")
    print("=" * 40)
    return 0


def _profiler(args: argparse.Namespace) -> int:
    """Profile the app."""
